// achievement rules built into it (rules\fh2_achievement_rules.json) and sends
// unlocks and progress to the OpenBox Achievements app over its pipe. Settings
// are in OpenBoxAchievements.ini beside the DLL; Extra Options' own INI is not
// touched.
