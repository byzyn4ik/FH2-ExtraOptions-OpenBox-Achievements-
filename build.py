"""Build the OpenBox Achievements plugin for Forza Horizon 2 Extra Options.

Usage: py build.py [--zig <zig.exe>] [--output out] [--test]

Writes:
  <output>/mods/OpenBox Achievements/mod.json
  <output>/mods/OpenBox Achievements/plugins/OpenBoxAchievements.dll
  <output>/mods/OpenBox Achievements/plugins/OpenBoxAchievements.ini
  <output>/tools/ach-replay.exe           (offline rules replay)
  <output>/tests/plugin_test.exe          (offline plugin test)
--test also runs tests/run_tests.py on the result. Nothing is installed.
Zig 0.15.2: --zig, else the ZIG environment variable, else zig on PATH.
"""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
SRC = HERE / "src"
RULES = HERE / "rules" / "fh2_achievement_rules.json"
MOD_NAME = "OpenBox Achievements"
DLL_NAME = "OpenBoxAchievements.dll"
ENGINE = ["ach_json.cpp", "ach_engine.cpp", "ach_store.cpp"]
PLUGIN = ENGINE + ["ach_service.cpp", "telemetry.cpp", "game_hooks.cpp", "openbox_app.cpp", "plugin.cpp"]
DELIMITER = "fh2rules"


def find_zig(given):
    for candidate in (given, os.environ.get("ZIG"), shutil.which("zig")):
        if candidate and Path(candidate).is_file():
            return Path(candidate).resolve()
    sys.exit("zig not found: pass --zig <zig.exe> (Zig 0.15.2) or set ZIG")


def rules_include(build):
    """The rules JSON as a C++ raw string, after checking it."""
    text = RULES.read_text(encoding="utf-8")
    data = json.loads(text)
    ids = data.get("Achievements")
    rules = data.get("Rules")
    if not isinstance(ids, list) or not isinstance(rules, list) or not rules:
        sys.exit(f"{RULES}: needs Achievements and Rules lists")
    known = set(ids)
    for rule in rules:
        if rule.get("Achievement") not in known or not rule.get("Event"):
            sys.exit(f"{RULES}: a rule for an unknown achievement or without an event: {rule}")
    if ")" + DELIMITER + '"' in text:
        sys.exit(f"{RULES}: contains the raw-string delimiter")
    build.mkdir(parents=True, exist_ok=True)
    include = build / "rules_data.inc"
    body = ("// Generated by build.py from rules/fh2_achievement_rules.json. Do not edit.\n"
            f"static const char kBuiltinRules[] = R\"{DELIMITER}({text}){DELIMITER}\";\n")
    if not include.is_file() or include.read_text(encoding="utf-8") != body:
        include.write_text(body, encoding="utf-8", newline="\n")
    print(f"rules: {len(rules)} rules for {len(ids)} achievements")
    return build


def run(command):
    print("zig", *[Path(str(part)).name if str(part).endswith((".cpp", ".exe", ".dll")) else str(part)
                   for part in command[1:]])
    subprocess.run([str(part) for part in command], check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    options = parser.parse_args()
    zig = find_zig(options.zig)
    output = options.output.resolve()
    build = output / "obj"
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    tools = output / "tools"
    tests = output / "tests"
    for folder in (plugins, tools, tests):
        folder.mkdir(parents=True, exist_ok=True)
    include = rules_include(build)

    common = [zig, "c++", "-target", "x86_64-windows-gnu", "-std=c++17", "-O2", "-Wall", "-Wextra", "-Werror",
              "-DUNICODE", "-D_UNICODE", "-fno-sanitize=all"]
    run([*common, "-shared", "-s", "-I", include, *[SRC / name for name in PLUGIN],
         "-luser32", "-ladvapi32", "-lshell32", "-lole32",
         "-Wl,--out-implib," + str(build / "OpenBoxAchievements.lib"), "-o", plugins / DLL_NAME])
    run([*common, "-municode", "-s", "-I", SRC, HERE / "tools" / "ach_replay.cpp", *[SRC / name for name in ENGINE],
         "-o", tools / "ach-replay.exe"])
    run([*common, "-municode", "-s", HERE / "tests" / "plugin_test.cpp", "-o", tests / "plugin_test.exe"])
    for stale in plugins.glob("*.lib"):
        stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / "OpenBoxAchievements.ini", plugins / "OpenBoxAchievements.ini")
    for path in (mod / "mod.json", plugins / DLL_NAME, plugins / "OpenBoxAchievements.ini",
                 tools / "ach-replay.exe", tests / "plugin_test.exe"):
        print(path)
    if options.test:
        subprocess.run([sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output)], check=True)


if __name__ == "__main__":
    main()
